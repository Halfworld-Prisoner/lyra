def _restore_symbols(text: str, marks: list) -> str:
    """把 ⟦n⟧ 还原成原符号;AI 弄丢的记号按顺序补回原位。"""
    import re as _re
    if not marks:
        return text
    used = set()

    def _sub(m):
        i = int(m.group(1))
        if 0 <= i < len(marks):
            used.add(i)
            return marks[i]
        return ""

