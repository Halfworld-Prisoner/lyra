# -*- coding: utf-8 -*-
"""修两个翻译开关的问题:

① 游戏运行时打开翻译 → 复制 DLL 报 WinError 1224(文件被游戏映射,覆盖不了)
   → 相同文件直接跳过;真被占用时给一句人话("先关游戏或点停止"),不再抛英文错误。
② 关掉翻译后游戏里仍是译文
   → 原因有两层:(a) 我们的接口不看开关,照样翻;(b) XUnity 自己有磁盘缓存
     (_AutoGeneratedTranslations.txt),喂过一次就一直用旧译文。
   修:接口按 translate.on 直接返回原文;关翻译时清掉 XUnity 的缓存文件。
"""
import io
import os

SRV = r"D:\Unity阅读器\webapp\server.py"
t = io.open(SRV, encoding="utf-8").read()

# ---------------- ① 复制逻辑:跳过相同文件 + 占用时给人话 ----------------
old_copy = '''                s = os.path.join(base, fn)
                t = os.path.join(d, rel)
                os.makedirs(os.path.dirname(t), exist_ok=True)
                try:
                    shutil.copy2(s, t)
                    n += 1
                    if rel not in TR_FILES:
                        TR_FILES.append(rel)
                except Exception as e:
                    return {"ok": False, "msg": f"复制 {rel} 失败:{e}"}'''
new_copy = '''                s = os.path.join(base, fn)
                t = os.path.join(d, rel)
                os.makedirs(os.path.dirname(t), exist_ok=True)
                # ★内容一样就别复制★:游戏运行时 DLL 被映射着,覆盖写会报
                #   WinError 1224(请求的操作无法在使用用户映射区域打开的文件上执行)。
                #   已经装过的游戏再点开关时文件本来就一样,跳过即可,不必碰它。
                try:
                    if os.path.isfile(t) and os.path.getsize(t) == os.path.getsize(s):
                        with open(s, "rb") as fa, open(t, "rb") as fb:
                            if fa.read() == fb.read():
                                if rel not in TR_FILES:
                                    TR_FILES.append(rel)
                                n += 1
                                continue
                except Exception:
                    pass
                try:
                    shutil.copy2(s, t)
                    n += 1
                    if rel not in TR_FILES:
                        TR_FILES.append(rel)
                except Exception as e:
                    msg = str(e)
                    if "1224" in msg or "being used by another process" in msg or "PermissionError" in type(e).__name__:
                        return {"ok": False,
                                "msg": "游戏正在运行,BepInEx 的文件被它占着,没法替换 —— "
                                       "请先退出游戏(或点「停止」结束游戏进程),再打开这个开关;" 
                                       "如果本来就装过,直接打开开关也行(文件一模一样时会跳过)"}
                    return {"ok": False, "msg": f"复制 {rel} 失败:{e}"}'''
assert old_copy in t
t = t.replace(old_copy, new_copy, 1)

# ---------------- ② 关闭时:清掉 XUnity 自己的译文缓存 ----------------
old_off = '''    # 关闭:只删清单里记过的文件
    gone = 0'''
new_off = '''    # ★关掉翻译时,必须清掉 XUnity 自己的缓存★
    # 否则它磁盘上存着 _AutoGeneratedTranslations.txt,重启游戏照样显示旧译文
    xcache_cleared = 0
    for sub in ("BepInEx\\\\Translation\\\\zh-CN\\\\Text", "Translation\\\\zh-CN\\\\Text"):
        p = os.path.join(d, sub)
        if os.path.isdir(p):
            for fn in os.listdir(p):
                if not fn.lower().endswith(".txt"):
                    continue
                fp = os.path.join(p, fn)
                try:
                    os.remove(fp)
                    xcache_cleared += 1
                except Exception:
                    pass
    # 关闭:只删清单里记过的文件
    gone = 0'''
assert old_off in t
t = t.replace(old_off, new_off, 1)

t = t.replace('''    _manifest_forget(d)
    return {"ok": True, "msg": f"已关闭 AI 翻译(移除 {gone} 个文件),重启游戏后恢复原文"}''',
              '''    _manifest_forget(d)
    if gone:
        return {"ok": True, "msg": f"已关闭 AI 翻译(移除 {gone} 个插件文件,清理 {xcache_cleared} 份译文缓存)"}
    return {"ok": True, "msg": "已关闭 AI 翻译 —— 游戏里会显示原文(插件文件被游戏占用就先留着,"
                               f"已清 {xcache_cleared} 份译文缓存);重启游戏后彻底生效"}''', 1)

# ---------------- ③ 接口按开关来:关着就直接给原文 ----------------
old_api = '''                q = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
                src = (q.get("text") or [""])[0]
                if not src:
                    return self._text("")
                try:
                    out = TRANSLATOR.get(src, cfgm.get().get("ai") or {})
                except Exception:
                    out = src
                _note_req(src, out)
                return self._text(out)'''
new_api = '''                q = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
                src = (q.get("text") or [""])[0]
                if not src:
                    return self._text("")
                # ★总开关在这里★:翻译关着的时候一律原样返回 ——
                #   插件还装在游戏里也没关系,游戏里看到的就是原文。
                #   (这样开关可以随时切,不用重装插件、也不用重启游戏)
                if not _tr_cfg().get("on"):
                    _note_req(src, src)
                    return self._text(src)
                try:
                    out = TRANSLATOR.get(src, cfgm.get().get("ai") or {})
                except Exception:
                    out = src
                _note_req(src, out)
                return self._text(out)'''
assert old_api in t
t = t.replace(old_api, new_api, 1)

io.open(SRV, "w", encoding="utf-8", newline="\n").write(t)
print("server.py 已修:①相同文件跳过+占用提示 ②关翻译清 XUnity 缓存 ③接口按开关返回原文")
