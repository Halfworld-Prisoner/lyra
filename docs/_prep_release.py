# -*- coding: utf-8 -*-
"""发布准备:把源码树这一轮的修复同步进桌面仓库 + 版本号 1.0 → 1.1 + 写更新日志。"""
import io
import os
import shutil

SRC = r"D:\Unity阅读器"
REPO = os.path.join(os.path.expanduser("~"), "Desktop", "Lyra")

FILES = [
    "core/ai.py",
    "core/translate.py",
    "core/data/t2s.txt",
    "webapp/server.py",
    "webapp/static/js/core.js",
    "webapp/static/js/views/settings_extra.js",
    "webapp/static/js/views/translate.js",
]

for rel in FILES:
    s = os.path.join(SRC, rel.replace("/", os.sep))
    d = os.path.join(REPO, rel.replace("/", os.sep))
    if not os.path.isfile(s):
        print("  !! 源文件不存在:", rel)
        continue
    os.makedirs(os.path.dirname(d), exist_ok=True)
    shutil.copy2(s, d)
    print("  同步 %-42s %6.1f KB" % (rel, os.path.getsize(d) / 1024))

# 版本号 1.0 → 1.1
p = os.path.join(REPO, "installer", "setup.c")
t = io.open(p, encoding="utf-8").read()
if 'APP_VERSION   L"1.0"' in t:
    t = t.replace('APP_VERSION   L"1.0"', 'APP_VERSION   L"1.1"', 1)
    io.open(p, "w", encoding="utf-8", newline="\n").write(t)
    print("  版本号 → 1.1(installer/setup.c)")
else:
    print("  --  版本号已是 1.1 或写法不同")

# 更新日志:把「未发布」改成 1.1.0,并补上这一轮的修复
p = os.path.join(REPO, "CHANGELOG.md")
t = io.open(p, encoding="utf-8").read()
head = t.split("\n## [1.0.0]")[0]
body = "\n## [1.0.0]" + t.split("\n## [1.0.0]", 1)[1]
NEW_HEAD = '''# 更新日志

本项目遵循 [语义化版本](https://semver.org/lang/zh-CN/)。

## [1.1.0] — 翻译与安装体验修复

### 修复
- **AI 的 API Key 保存后变成空的**(严重):设置页每 0.4 秒按状态重绘,玩家输完 Key 去点「保存」时
  焦点已离开输入框,重绘就把刚输入的内容当成过期值清掉。现在给输入框加了"脏值保护":
  **玩家碰过的输入框在保存成功前不许被重绘覆盖**(AI 的 5 个输入框与 3 个滑条、翻译页等待时间均已接入)。
- **AI 报错信息含糊**:原来所有失败都提示"检查 Key/网络"。现在按类型分开:Key 不对(401/403)、
  接口地址不对(404)、太频繁或额度用完(429)、服务器出错(5xx)、模型名写错(400)、超时与连不上。
- **繁转简不全,角色名残留繁体**(如 格蘭特尼、奧斯卡):内置简繁表换成 **OpenCC 权威表(4148 条)**;
  并新增"本地直转"快路径 —— 短名字/界面词直接本地转换,不花 token、不等待、也不会被模型"贴心保留繁体"。
- **译文会丢/改符号**(「」《》，。、?——♪ 等):新增**符号保护** —— 把符号换成占位记号交给 AI,
  回来按原文逐字对齐还原;数量对不上就带着"缺了哪个、几次"重试一次;**仍对不上就让这一句显示原文**,
  绝不输出乱码。
- **关闭翻译后游戏里仍是中文**:原因有两层 —— ① 我们的接口不看开关(已改为服务端总开关,
  关着时一律返回原文);② XUnity 自己有磁盘缓存 `_AutoGeneratedTranslations.txt`,里面存着
  「Config=Config」「Language=Language」这类**毒记录**(关着开关时问出来的),导致标题页永远英文。
  现在**每次切换开关都会清掉这份缓存**。
- **游戏运行时打不开翻译开关**(WinError 1224 请求的操作无法在使用用户映射区域打开的文件上执行):
  文件被游戏映射时无法覆盖。现在内容相同就跳过复制;确实需要替换时给一句人话("请先退出游戏")。
- **方框字(□)**:游戏自带的是繁体字体,繁转简后出现的简体字缺字形。现在给游戏内 XUnity 写上
  `OverrideFont / OverrideFontTextMeshPro / FallbackFontTextMeshPro = Microsoft YaHei`,
  由系统字体动态生成中文字形(可在翻译页关闭)。
- **角色配音页选完声音一秒后被刷回**:这一页任何下拉/输入改动后 15 秒内不重建 DOM。
- **鼠标按下期间不再重建页面 DOM**:修复"点了没反应 / 下拉框刚展开就被掀掉"。
- **卸载程序点确认后没有真正卸载**:确认后必须继续走"复制自己到 %TEMP% 再重跑"的收尾。
- **滚动条没有隐藏**、**安装器 Logo 不是指定图片**、**安装器路径框空白**、**项目与安装目录英文名**。

### 变更
- 安装程序页面只介绍主功能;窗口放大,说明块不再被状态行压掉。
- 翻译开关现在**即时生效**(不必重启游戏即可回到原文/开始翻译;屏幕上已显示的文字需刷新一次)。
- 安装程序/卸载程序均使用 WebView2 网页界面,环境缺失时自动回退系统界面。

### 已知问题
- 部分游戏的**主菜单按钮**(如图中 `START / LOAD / CONFIG / GALLERY / EXTRA / EXIT`)在插件日志与
  XUnity 日志中都不出现,判断为**图片/精灵**而非文字组件,文字翻译无法覆盖;后续可能以贴图替换或
  悬浮层方式处理。
- `Knights College 2` / `Astatos` 的剧情文本尚未接入 LDC 挂钩(需单独做引擎适配)。
'''
io.open(p, "w", encoding="utf-8", newline="\n").write(NEW_HEAD + body)
print("  更新日志已写入 1.1.0 小节")
