def _note_req(src: str, out: str) -> None:
    s = (src or '').strip().replace('\n', ' ')
    if not s or len(s) > 40:
        return
    try:
        with _RECENT_LOCK:
            _RECENT_REQ.append({'src': s, 'out': (out or '').strip()[:40],
                                'changed': (out or '').strip() != s})
            del _RECENT_REQ[:-40]
    except Exception:
        pass


