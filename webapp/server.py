def clear_xunity_cache(game: dict) -> int:
    r"""清掉 XUnity 自己的译文缓存文件。

    ★为什么必须清★:XUnity 把"原文=译文"记在
      BepInEx\Translation\<lang>\Text\_AutoGeneratedTranslations.txt 里。
    翻译开关关着的时候它来问,我们回的是原文,于是它存下一堆
    「Config=Config」「Language=Language」这种毒记录 —— 之后就算打开开关,
    它也认为"这句翻过了",标题页永远停在英文。切换开关时清掉即可根治。
    """
    d = (game or {}).get("dir") or ""
    if not d:
        return 0
    n = 0
    for sub in ("BepInEx\\Translation", "Translation"):
        root = os.path.join(d, sub)
        if not os.path.isdir(root):
            continue
        for base, _dirs, files in os.walk(root):
            for fn in files:
                if fn.lower().endswith(".txt"):
                    try:
                        os.remove(os.path.join(base, fn))
                        n += 1
                    except Exception:
                        pass
    return n


def translate_install(game: dict, on: bool = True) -> dict:
    """把 XUnity.AutoTranslator(AI 汉化)装进/移出游戏目录。

    只动我们自己放进去的那几个文件,并且记在 _聆阅_已安装清单.json 里 ——
    和 LDC 一样:**卸载时绝不碰玩家自己装的东西**。
    """
    d = (game or {}).get("dir") or ""
    if not d or not os.path.isdir(d):
        return {"ok": False, "msg": "找不到游戏目录"}
    src = translate_payload_dir(game)
    if on:
        if not os.path.isdir(src):
            return {"ok": False, "msg": "安装包里缺少翻译插件文件(重新安装 Lyra 可修复)"}
        if not (game or {}).get("installed"):
            return {"ok": False, "msg": "这台游戏的 LDC 还没装 —— 先点「安装 LDC」"}
        n = 0
        for base, _dirs, files in os.walk(src):
            for fn in files:
                rel = os.path.relpath(os.path.join(base, fn), src)
                # 说明.txt 是给我们自己看的,不用塞进玩家游戏目录
                if fn == "说明.txt" or rel.startswith("说明"):
                    continue
                s = os.path.join(base, fn)
                t = os.path.join(d, rel)
                os.makedirs(os.path.dirname(t), exist_ok=True)
                # ★内容一样就别复制★:游戏运行时 DLL 被映射着,覆盖写会报
                #   WinError 1224(请求的操作无法在使用用户映射区域打开的文件上执行)。
                #   已经装过的游戏再点开关时文件本来就一样,跳过即可,不必碰它。
                try:
                    if os.path.isfile(t) and os.path.getsize(t) == os.path.getsize(s):
                        with open(s, "rb") as fa, open(t, "rb") as fb:
                            if fa.read() == fb.read():
                                if rel not in TR_FILES:
                                    TR_FILES.append(rel)
                                n += 1
                                continue
                except Exception:
                    pass
                try:
                    shutil.copy2(s, t)
                    n += 1
                    if rel not in TR_FILES:
                        TR_FILES.append(rel)
                except Exception as e:
                    msg = str(e)
                    if "1224" in msg or "being used by another process" in msg or "PermissionError" in type(e).__name__:
                        return {"ok": False,
                                "msg": "游戏正在运行,BepInEx 的文件被它占着,没法替换 —— "
                                       "请先退出游戏(或点「停止」结束游戏进程),再切换这个开关"}
                    return {"ok": False, "msg": f"复制 {rel} 失败:{e}"}
        _manifest_remember(d, TR_FILES)
        cleared = clear_xunity_cache(game)          # 清掉旧的"原文=原文"缓存
        return {"ok": True,
                "msg": f"已启用 AI 翻译({n} 个文件,清理 {cleared} 份旧译文缓存)—— "
                       f"**重启游戏**后标题页与菜单的文字也会变成中文"}
    # ★关掉翻译时,必须清掉 XUnity 自己的缓存★
    # 否则它磁盘上存着 _AutoGeneratedTranslations.txt,重启游戏照样显示旧译文
    xcache_cleared = clear_xunity_cache(game)
    # 关闭:只删清单里记过的文件
    gone = 0
    for rel in list(TR_FILES):
        t = os.path.join(d, rel)
        if os.path.isfile(t):
            try:
                os.remove(t)
                gone += 1
            except Exception:
                pass
    for sub in ("BepInEx\\plugins\\XUnity.AutoTranslator",
                "BepInEx\\plugins\\XUnity.ResourceRedirector"):
        p = os.path.join(d, sub)
        try:
            if os.path.isdir(p) and not os.listdir(p):
                os.rmdir(p)
        except Exception:
            pass
    _manifest_forget(d)
    if gone:
        return {"ok": True, "msg": f"已关闭 AI 翻译(移除 {gone} 个插件文件,清理 {xcache_cleared} 份译文缓存)"}
    return {"ok": True, "msg": "已关闭 AI 翻译 —— 游戏里会显示原文(插件文件被游戏占用就先留着,"
                               f"已清 {xcache_cleared} 份译文缓存);重启游戏后彻底生效"}


def _manifest_path(game_dir: str) -> str:
    return os.path.join(game_dir, storyhook.MANIFEST)


def _manifest_remember(game_dir: str, rels):
    try:
        p = _manifest_path(game_dir)
        data = {}
        if os.path.isfile(p):
            data = json.load(open(p, encoding="utf-8-sig"))
        data["translate"] = sorted(set(list(data.get("translate") or []) + list(rels)))
        json.dump(data, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    except Exception:
        pass


def _manifest_forget(game_dir: str):
    try:
        p = _manifest_path(game_dir)
        if not os.path.isfile(p):
            return
        data = json.load(open(p, encoding="utf-8-sig"))
        data.pop("translate", None)
        json.dump(data, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    except Exception:
        pass


