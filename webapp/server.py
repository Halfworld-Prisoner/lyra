                ack = _read_click_ack()
                if ack is None:
                    return self._json({"ok": False, "msg": "插件没有回应 —— 游戏里的 LDC 可能是旧版,"
                                                          "重新点一次「安装 LDC」并重启游戏"})
                ok = ack[0] == "ok"
                msg = ("静默推进成功:" if ok else "静默推进失败:") + (ack[1] or "")
